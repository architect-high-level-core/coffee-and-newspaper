#!/usr/bin/env python3
"""Precompute SEO helper data for the Jekyll site. Run from the repo root:

    python3 scripts/build_seo_data.py

Writes
  _data/related.yml  – for every post (keyed by its `_posts/...` path) the 3
                       most related posts, scored by shared tags (rare tags
                       count more) and shared title words.
  _data/images.yml   – pixel width/height of every image in assets/img, used
                       for <img width/height> and og:image:width/height.

Both files are optional at build time: posts without an entry fall back to the
most recent posts, images without an entry are rendered without dimensions.
Needs: python3, PyYAML, Pillow (pip install pyyaml pillow).
"""
import glob, math, os, re
from collections import Counter
import yaml

STOP = set("""a an and are as at be but by for from has have how in into is it its of on or our that the
their this to was what when where which who why will with you your new news ai vs more than after about
can do does not now one two three four five six seven eight nine ten plus they them we us der die das und
ein eine mit von für im ist was wie zu den des""".split())
GENERIC_TAGS = {"ai", "ki", "ai news"}

def load_posts():
    posts = []
    for f in sorted(glob.glob('_posts/*.md')):
        src = open(f, encoding='utf-8').read()
        m = re.match(r'---\n(.*?)\n---\n', src, re.S)
        fm = yaml.safe_load(m.group(1)) if m else {}
        if fm.get('published') is False:
            continue
        tags = {str(t).lower() for t in (fm.get('tags') or [])} - GENERIC_TAGS
        words = {w for w in re.findall(r"[a-z0-9äöüß][a-z0-9äöüß.\-]+", str(fm.get('title', '')).lower())
                 if w not in STOP and len(w) > 2}
        posts.append({'path': f, 'tags': tags, 'words': words, 'lang': fm.get('lang', 'en')})
    return posts

def related(posts, n=3):
    df = Counter(t for p in posts for t in p['tags'])
    wdf = Counter(w for p in posts for w in p['words'])
    N = len(posts)
    out = {}
    for i, p in enumerate(posts):
        scored = []
        for j, q in enumerate(posts):
            if i == j:
                continue
            s = sum(math.log(N / df[t]) + 1 for t in p['tags'] & q['tags'])
            s += 0.5 * sum(math.log(N / wdf[w]) + 1 for w in p['words'] & q['words'])
            if p['lang'] == q['lang']:
                s += 0.25
            s += j / (N * 100.0)          # tie-break: newer first
            scored.append((s, q['path']))
        scored.sort(reverse=True)
        out[p['path']] = [path for s, path in scored[:n]]
    return out

def image_sizes():
    from PIL import Image
    sizes = {}
    for f in sorted(glob.glob('assets/img/*')):
        try:
            with Image.open(f) as im:
                sizes['/' + f] = {'w': im.width, 'h': im.height}
        except Exception:
            pass
    return sizes

def dump(path, data, header):
    os.makedirs('_data', exist_ok=True)
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(header + '\n')
        yaml.safe_dump(data, fh, allow_unicode=True, sort_keys=True, default_flow_style=False)

if __name__ == '__main__':
    posts = load_posts()
    dump('_data/related.yml', related(posts), '# Generated by scripts/build_seo_data.py – do not edit by hand.')
    dump('_data/images.yml', image_sizes(), '# Generated by scripts/build_seo_data.py – do not edit by hand.')
    print(f'related.yml: {len(posts)} posts; images.yml written')
